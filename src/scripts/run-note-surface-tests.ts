import assert from 'node:assert/strict';
import { collectNoteSurfaces, noteSurfaceArea, noteSurfaceJobs, validNoteSurfaceSelection } from '../lib/note-surfaces';
import { calculateJointFinishingCost } from '../lib/joint-finishing-cost';
const opening = { title: 'opening dicht maken', length: '2200', width: '950', height: '', thickness: '' };
assert.equal(noteSurfaceArea(opening), 2.09);
assert.equal(noteSurfaceArea({ ...opening, width: '', height: '950' }), 2.09);
assert.equal(noteSurfaceArea({ ...opening, width: '950,5 mm' }), 2.0911);
assert.equal(noteSurfaceArea({ ...opening, width: '', thickness: '950' }), 0, 'Dikte niet als oppervlak gebruiken');
assert.equal(noteSurfaceArea({ ...opening, width: 'ongeveer 950' }), 0, 'Geen gegokte maten');
assert.equal(noteSurfaceArea({ ...opening, height: '3000' }, 'wand'), 6.6);
assert.equal(noteSurfaceArea({ ...opening, height: '3000' }, 'plafond'), 2.09);
const candidates = collectNoteSurfaces([{ title: '', notes: 'Deur verwijderen en opening dichtzetten', maatwerkLines: [opening, { title: '', length: '', width: '', height: '', thickness: '' }] }]);
assert.equal(candidates.length, 1, 'Lege standaardregel negeren');
const fingerprint = JSON.stringify(candidates);
const selection = validNoteSurfaceSelection({ fingerprint, surfaces: [{key: '0:0', kind: 'wand'}] }, candidates, fingerprint);
assert.ok(selection);
const result = calculateJointFinishingCost(noteSurfaceJobs(candidates, selection));
assert.equal(result.area, 2.09);
assert.equal(result.amount, 1.61);
assert.deepEqual(result.errors, []);
assert.equal(validNoteSurfaceSelection(selection, candidates, fingerprint + 'changed'), null, 'Gewijzigde notities vragen nieuwe keuze');
assert.equal(validNoteSurfaceSelection({fingerprint, surfaces:[{key:'hallucinatie', kind:'wand'}]}, candidates, fingerprint), null);
assert.equal(validNoteSurfaceSelection({fingerprint, surfaces:[{key:'0:0', kind:'vloer'}]}, candidates, fingerprint), null);
assert.equal(validNoteSurfaceSelection({fingerprint, surfaces:[{key:'0:0', kind:'wand'}, {key:'0:0', kind:'wand'}]}, candidates, fingerprint), null);
const changed = [{...candidates[0], width: ''}];
assert.equal(validNoteSurfaceSelection(selection, changed, fingerprint), null, 'Geen prijs zonder geldige maten');
console.log('Notitie-oppervlaktes geslaagd: 2,09 m², dimensies, lege regels, nadenkosten, gewijzigde bron en ongeldige AI-keuzes.');
